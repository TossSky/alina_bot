def generate_contextual_prompt(
    base_personality: str,
    user_context: Dict,
    conversation_history: List[Dict]
) -> str:
    """
    Генерирует промпт БЕЗ излишних правил и ограничений.
    Только мягкие напоминания о контексте.
    """
    
    parts = [base_personality]
    
    # Время суток (мягко)
    time_context = get_time_context()
    if time_context:
        parts.append(f"\n(сейчас {time_context})")
    
    # Настроение (если есть)
    mood = get_mood_modifier()
    if mood:
        parts.append(f"\n({mood})")
    
    # Отношения (очень мягко)
    relationship = user_context.get("relationship", "stranger")
    if relationship == "friend":
        parts.append("\n(вы уже друзья, можешь быть открытее)")
    elif relationship == "close_friend":
        parts.append("\n(вы близкие друзья, никаких барьеров)")
    elif relationship == "best_friend":
        parts.append("\n(лучшие друзья, полная откровенность)")
    
    # Память о пользователе (если есть)
    if user_context.get("user_memory"):
        memory_parts = []
        for key, value in user_context["user_memory"].items():
            if key == "name":
                memory_parts.append(f"зовут {value}")
            elif key == "work":
                memory_parts.append(f"работает {value}")
            elif key == "pet":
                memory_parts.append(f"есть {value}")
        
        if memory_parts:
            parts.append(f"\n(помнишь о собеседнике: {', '.join(memory_parts)})")
    
    # НЕ добавляем жёсткие правила про эмодзи
    # НЕ добавляем ВНИМАНИЕ, СТРОГО и т.д.
    # НЕ добавляем сложные инструкции
    
    return "\n".join(parts)

