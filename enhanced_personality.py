class SimplePatternDetector:
    """Упрощенный детектор для критических случаев."""
    
    def __init__(self):
        self.spam_history = []
        self.last_topics = []
    
    def check_spam(self, message: str, user_id: int) -> int:
        """Проверяет только явный спам."""
        normalized = message.lower().strip()
        
        # Храним последние 5 сообщений
        self.spam_history.append(normalized)
        if len(self.spam_history) > 5:
            self.spam_history.pop(0)
        
        # Считаем повторения
        if self.spam_history.count(normalized) > 3:
            return self.spam_history.count(normalized)
        
        return 0
    
    def is_sensitive_topic(self, message: str) -> bool:
        """Проверяет только критически чувствительные темы."""
        sensitive = ["суицид", "убить себя", "не хочу жить", "конец всему"]
        message_lower = message.lower()
        return any(word in message_lower for word in sensitive)

