def get_emotional_context(message: str) -> Optional[str]:
    """Определяет эмоциональный контекст БЕЗ формализма."""
    message_lower = message.lower()
    
    # Грусть
    if any(word in message_lower for word in ["грустно", "плохо", "одиноко", "устал"]):
        return "(собеседник грустит, поддержи)"
    
    # Радость  
    if any(word in message_lower for word in ["круто", "супер", "ура", "класс"]):
        return "(собеседник радуется, раздели радость)"
    
    # Злость
    if any(word in message_lower for word in ["бесит", "злюсь", "ненавижу", "достало"]):
        return "(собеседник злится, дай выговориться)"
    
    return None

